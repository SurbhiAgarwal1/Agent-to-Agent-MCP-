import React, { useState, useEffect } from 'react';
import useAuth from '../hooks/useAuth';
import { listAuditLogs } from '../api/admin';
import Card from '../components/common/Card';
import LoadingSpinner from '../components/common/LoadingSpinner';
import EmptyState from '../components/common/EmptyState';

export default function NotificationsPage() {
  const { user } = useAuth();
  const isAdmin = user?.role === 'ADMIN';

  const [logs, setLogs] = useState([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);

  useEffect(() => {
    let isMounted = true;
    if (isAdmin) {
      setLoading(true);
      listAuditLogs({ limit: 50 })
        .then((data) => {
          if (isMounted) {
            // Filter logs related to notifications or coordinator dispatches
            const notificationLogs = (data || []).filter(
              (item) =>
                item.action?.includes('COORDINATE') ||
                item.action?.includes('MATCH') ||
                item.action?.includes('REQUEST')
            );
            setLogs(notificationLogs);
          }
        })
        .catch((err) => {
          if (isMounted) setError(err.message || 'Failed to load dispatch events.');
        })
        .finally(() => {
          if (isMounted) setLoading(false);
        });
    }
    return () => {
      isMounted = false;
    };
  }, [isAdmin]);

  return (
    <div>
      <div style={{ marginBottom: '1.5rem' }}>
        <h1 style={{ fontSize: '1.75rem', fontWeight: 700, margin: 0, color: 'var(--color-text-main)' }}>
          Agent Notification Dispatches
        </h1>
        <p className="text-secondary" style={{ marginTop: '0.25rem', fontSize: '0.9375rem' }}>
          Real-time alerts generated by the Notification Agent during blood coordination workflows
        </p>
      </div>

      <div className="alert alert-info" style={{ marginBottom: '1.5rem' }}>
        <strong>Protocol Dispatch Architecture:</strong> In this A2A system, notifications are autonomously dispatched
        by the <code>NotificationAgent</code> to hospitals, candidate blood banks, and donors upon fulfillment plan resolution.
      </div>

      {isAdmin ? (
        <Card title="Recent Notification & Lifecycle Events">
          {loading && <LoadingSpinner message="Retrieving event dispatches..." />}
          {error && (
            <div className="alert alert-error" style={{ marginBottom: '1rem' }}>
              {error}
            </div>
          )}

          {!loading && !error && logs.length === 0 && (
            <EmptyState
              title="No Dispatch Events Recorded"
              message="No coordinator or notification events have been logged yet."
            />
          )}

          {!loading && !error && logs.length > 0 && (
            <div className="table-responsive">
              <table className="table">
                <thead>
                  <tr>
                    <th>Log ID</th>
                    <th>Action</th>
                    <th>Resource</th>
                    <th>Target ID</th>
                    <th>Timestamp</th>
                  </tr>
                </thead>
                <tbody>
                  {logs.map((log) => (
                    <tr key={log.log_id || log.id}>
                      <td><strong>#{log.log_id || log.id}</strong></td>
                      <td>
                        <span className="badge badge-neutral">{log.action}</span>
                      </td>
                      <td>{log.resource}</td>
                      <td>#{log.resource_id}</td>
                      <td className="text-secondary" style={{ fontSize: '0.8125rem' }}>
                        {log.timestamp ? new Date(log.timestamp).toLocaleString() : '—'}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </Card>
      ) : (
        <Card title="Hospital Dispatch Status">
          <p className="text-secondary" style={{ lineHeight: 1.6 }}>
            Your account is assigned as <strong>{user?.role}</strong>. Urgent alerts regarding your hospital's
            requests are surfaced inside individual Request views when the multi-agent coordination pipeline
            executes.
          </p>
          <div style={{ marginTop: '1rem' }}>
            <span className="badge badge-success" style={{ fontSize: '0.875rem' }}>
              Notification Agent: Active on A2A Network
            </span>
          </div>
        </Card>
      )}
    </div>
  );
}
